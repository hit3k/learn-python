print("You are standing in front of two magical doors.")
choice = input("Type 1 to enter the Gold Door, or Type 2 to enter the Silver Door: ")

if choice == "1":
    print("The Gold Door opens! You find a chest full of dragon eggs!")
elif choice == "2":
    print("The Silver Door creaks open... A friendly wizard hands you a magic wand!")
else:
    print("You hesitated too long! A giant turtle stole your shoes.")
